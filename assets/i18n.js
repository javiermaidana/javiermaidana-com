(function(){
  var KEY='tbx-lang';
  function get(o,p){return p.split('.').reduce(function(a,k){return a==null?a:a[k];},o);}
  function apply(lang){
    var t=window.TBX_COPY[lang]||window.TBX_COPY.en;
    document.documentElement.lang=lang;
    document.querySelectorAll('[data-i18n]').forEach(function(el){var v=get(t,el.getAttribute('data-i18n'));if(v!=null)el.textContent=v;});
    document.querySelectorAll('[data-i18n-ph]').forEach(function(el){var v=get(t,el.getAttribute('data-i18n-ph'));if(v!=null)el.setAttribute('placeholder',v);});
    document.querySelectorAll('.lang button').forEach(function(b){b.classList.toggle('on',b.getAttribute('data-lang')===lang);});
    window.TBX_LANG=lang;
  }
  var saved=null;try{saved=localStorage.getItem(KEY);}catch(e){}
  var initial=saved||((navigator.language||'en').toLowerCase().indexOf('es')===0?'es':'en');
  document.addEventListener('DOMContentLoaded',function(){
    apply(initial);
    document.querySelectorAll('.lang button').forEach(function(b){b.addEventListener('click',function(){var l=b.getAttribute('data-lang');try{localStorage.setItem(KEY,l);}catch(e){}apply(l);});});
  });
})();
